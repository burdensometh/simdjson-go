package simdjson

// addNumber parses the number at the start of buf and, on success, writes the
// matching tag/value pair to the tape. It is shared by the SIMD stage 2
// machine and the portable pure Go parser so that number classification
// (int/uint/float and overflow flags) is identical on every architecture.
func addNumber(buf []byte, pj *ParsedJson) bool {
	tag, val := parseNumber(buf)
	if tag == 0 {
		return false
	}
	pj.writeTapeTagValFlags(tag, val)
	return true
}

// structural chars here are
